# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def isPalindrome(self, head: Optional[ListNode]) -> bool:
        self.next = next

        palindrome_set = set()

        if not head:
            return False

        if (head.node != 0):
            palindrome_set.append(head)
            head.next = next
            return True
        
        return True